// Generate a simplified summary for display
export function generateApplicationSummary(application: ApplicationForm): {
  label: string;
  value: string;
  icon: string;
}[] {
  return [
    { label: 'Name', value: application.personalInfo.fullName, icon: '👤' },
    { label: 'Passport', value: application.personalInfo.passportNumber, icon: '🔢' },
    { label: 'Nationality', value: application.personalInfo.nationality, icon: '🌍' },
    { label: 'Email', value: application.personalInfo.contactEmail, icon: '📧' },
    { label: 'Property', value: application.rentalDetails.propertyAddress, icon: '🏠' },
    { label: 'Weekly Rent', value: `$${application.rentalDetails.weeklyRent}`, icon: '💰' },
    { label: 'Move-in', value: application.rentalDetails.preferredMoveInDate, icon: '📅' },
    { label: 'Match Score', value: `${application.scores.matchScore}%`, icon: '🎯' },
    { label: 'Map Score', value: `${application.scores.mapScore}%`, icon: '🗺️' },
    { label: 'Total Score', value: `${application.scores.totalScore}%`, icon: '⭐' },
  ];
}

