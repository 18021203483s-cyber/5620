import { UserProfile, PassportInfo, ScoredProperty, ApplicationForm, RentalApplication } from './types';
import { formatPassportSummary } from './document-agent';

// Generate a complete rental application
export function generateApplication(
  userProfile: UserProfile,
  passportInfo: PassportInfo,
  selectedProperty: ScoredProperty,
  additionalNotes: string = ''
): RentalApplication {
  return {
    userProfile,
    passportInfo,
    selectedProperty,
    additionalNotes,
    submittedAt: new Date()
  };
}

// Format application as a display-friendly object
export function formatApplicationForDisplay(application: RentalApplication): ApplicationForm {
  return {
    personalInfo: {
      fullName: application.passportInfo.fullName,
      passportNumber: application.passportInfo.passportNumber,
      nationality: application.passportInfo.nationality,
      dateOfBirth: application.passportInfo.dateOfBirth,
      contactEmail: application.userProfile.contact || 'Not provided'
    },
    rentalDetails: {
      selectedProperty: `${application.selectedProperty.address}, ${application.selectedProperty.suburb}`,
      propertyAddress: application.selectedProperty.address,
      weeklyRent: application.selectedProperty.price,
      preferredMoveInDate: application.userProfile.moveInDate || 'Flexible'
    },
    scores: {
      matchScore: application.selectedProperty.matchScore,
      mapScore: application.selectedProperty.mapScore,
      totalScore: application.selectedProperty.totalScore
    }
  };
}

